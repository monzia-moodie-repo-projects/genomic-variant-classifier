def test_the_corpus_is_present_and_complete():
    idx = _index()
    assert idx["schema"] == 1
    entries = idx["entries"]
    assert len(entries) == 16, sorted(entries)
    for name, meta in entries.items():
        p = _FIX / meta["pickle"]
        assert p.is_file(), name
        assert p.stat().st_size == meta["pickle_bytes"], name


def test_every_pickle_matches_its_recorded_digest():
    """A fixture edited by hand is not a witness."""
    import hashlib
    for name, meta in _index()["entries"].items():
        blob = (_FIX / meta["pickle"]).read_bytes()
        assert hashlib.sha256(blob).hexdigest() == meta["pickle_sha256"], name


