"""The frozen answer to what a scientific identity MEANS, before its owner moves.

Phase 1C Unit 3A.0. Created 2026-09-02.

WHY A FROZEN CORPUS
-------------------
Unit 3A moves canonical ownership of the identity substrate from
`monitoring.drift` into `provenance`. Its governing invariant is:

    UNIT 3A MAY CHANGE WHERE A SCIENTIFIC IDENTITY IS DEFINED.
    IT MUST NOT CHANGE WHAT THAT IDENTITY MEANS.

An invariant checked only against post-move code proves nothing, because the
post-move code agrees with itself. These fixtures were generated from the
PRE-MOVE tree at 4805033 and committed, so afterwards they are an independent
witness rather than a restatement.

THREE ORACLES, WHICH FAIL FOR DIFFERENT REASONS
-----------------------------------------------
BEHAVIOURAL   the existing suite -- every prior node identity still passes
SEMANTIC      `semantic.json` -- canonical keys, records, digests, describes
PERSISTENCE   the pickles -- old bytes still resolve to the canonical classes

A single implementation defect rarely trips all three, and a defect that trips
none is not a defect this migration can cause.

AND ONE FILE THAT MUST CHANGE
-----------------------------
`ownership.json` records `__module__.__qualname__` per entry. It is the ONE
thing Unit 3A is meant to alter, so it is deliberately kept OUT of
`semantic.json`. Before the move every entry reads `monitoring.drift.*`; after
it, every entry must read `provenance.*`. `test_ownership_is_recorded_as_the_
PRE_MOVE_state` pins the baseline so a later unit can prove the move happened
rather than assuming it.

WHY PERSISTENCE MATTERS HERE SPECIFICALLY
-----------------------------------------
The 2026-09-02 census found no tracked file containing BOTH a serialization
mechanism and one of these types. That establishes no DIRECT STATIC coupling.
It does NOT establish that no persisted object graph contains one: a
`TrainingState` holding a `SourceManifest` in one module, pickled by
`joblib.dump` in another, is invisible to same-file co-occurrence.

This repository has already paid for a class relocation once --
`scripts/migrate_pickles.py` exists, and `variant_ensemble.py` sets
`_CNN1DModule.__module__` explicitly with a test asserting it, after a recorded
cross-platform unpickle failure.

Acronyms: SHA-256 = Secure Hash Algorithm 256-bit; JSON = JavaScript Object
Notation.

Author: Monzia Moodie
"""
from __future__ import annotations

import json
import pickle
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[2]
_FIX = _ROOT / "tests" / "fixtures" / "provenance_migration_v1"

_INDEX = _FIX / "index.json"
_SEMANTIC = _FIX / "semantic.json"
_OWNERSHIP = _FIX / "ownership.json"

pytestmark = pytest.mark.skipif(
    not _INDEX.is_file(),
    reason="the migration corpus is absent; it is generated by "
           "scripts/dev/build_provenance_migration_fixtures.py and MUST be "
           "present in the repository -- this must not skip in CI",
)


def _index() -> dict:
    return json.loads(_INDEX.read_text(encoding="utf-8"))


def _names() -> list[str]:
    return sorted(_index()["entries"])


def _load(name: str):
    return pickle.loads((_FIX / (name + ".pickle")).read_bytes())


def _semantic_of(obj) -> dict:
    """The SAME projection the generator used. Kept in step by a test below."""
    out = {"type_name": type(obj).__name__}
    for attr in ("canonical_key", "digest", "evidence_digest"):
        if hasattr(obj, attr):
            value = getattr(obj, attr)
            out[attr] = list(value) if isinstance(value, tuple) else value
    for meth in ("as_record", "describe"):
        if hasattr(obj, meth):
            out[meth] = getattr(obj, meth)()
    return out


