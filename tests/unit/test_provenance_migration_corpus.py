def test_ownership_is_recorded_as_the_PRE_MOVE_state():
    """Kept OUT of semantic.json deliberately.

    `__module__` is the ONE thing Unit 3A changes, so including it in the
    semantic oracle would make that oracle fail by construction and prove
    nothing. Recording it separately lets a later unit prove the move HAPPENED.
    """
    own = json.loads(_OWNERSHIP.read_text(encoding="utf-8"))
    assert len(own) == 16
    assert all(v.startswith("genomic_variant_classifier.monitoring.drift.")
               for v in own.values()), own


def test_semantic_json_carries_NO_module():
    frozen = json.loads(_SEMANTIC.read_text(encoding="utf-8"))
    assert not any("module" in e for e in frozen.values())
