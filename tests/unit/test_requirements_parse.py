def _write(text: str, name: str = "r.txt", *, binary: bool = False) -> Path:
    d = Path(tempfile.mkdtemp())
    p = d / name
    if binary:
        open(p, "wb").write(text)
    else:
        io.open(p, "w", encoding="utf-8", newline="\n").write(text)
    return p


