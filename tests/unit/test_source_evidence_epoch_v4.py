def test_EVERY_role_subset_serialises_sorted():
    """The property, not the sample.

    MEASURED BY SABOTAGE 2026-09-02: replacing
    `sorted(r.value for r in self.roles)` with an unsorted comprehension
    changed NO test -- even under a FIXED hash seed -- because the corpus uses
    `{observation, label}`, one of only three subsets of five roles whose
    natural iteration order happens to equal its sorted order.

    MEASURED across seeds 0, 1, 7 and 42: between TWENTY and TWENTY-THREE of
    the twenty-six non-trivial subsets iterate unsorted. Asserting the
    property over every subset cannot depend on which one a fixture chose.
    """
    import itertools

    from genomic_variant_classifier.provenance import (
        ArtifactKind, CoordinateContext, SourceArtifactIdentity,
        SourceArtifactKey, SourceDependency, SourceRole)

    identity = SourceArtifactIdentity(
        key=SourceArtifactKey("clinvar", ArtifactKind.PRIMARY_RELEASE),
        release_id="2026-08",
        coordinate_context=CoordinateContext.assembly("GRCh38"),
        artifact_sha256=hashlib.sha256(b"role-subset-probe").hexdigest())

    roles = list(SourceRole)
    checked = 0
    for size in range(1, len(roles) + 1):
        for combo in itertools.combinations(roles, size):
            dep = SourceDependency(identity=identity,
                                   roles=frozenset(combo))
            got = dep.as_record()["roles"]
            checked += 1
            assert got == sorted(got), (combo, got)
            assert got == sorted(r.value for r in combo), (combo, got)
    assert checked == 2 ** len(roles) - 1 == 31


