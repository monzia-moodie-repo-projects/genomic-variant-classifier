def _generator():
    """Load the committed freeze script and return its module.

    The test calls the SAME `build()` the fixture was written by, so the two
    cannot drift apart. Re-implementing the case construction here would
    reproduce the `_semantic`/`_semantic_of` hazard: two projections that agree
    today and silently diverge later.
    """
    import importlib.util
    import sys

    path = (Path(__file__).resolve().parents[2] / "scripts" / "dev"
            / "freeze_source_evidence_epoch.py")
    if not path.is_file():                                  # pragma: no cover
        pytest.skip("the freeze script is absent: {}".format(path))
    spec = importlib.util.spec_from_file_location("_epoch_freeze", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["_epoch_freeze"] = mod
    argv = sys.argv
    sys.argv = ["_epoch_freeze"]
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.argv = argv
        sys.modules.pop("_epoch_freeze", None)
    return mod


def test_the_freeze_script_REFUSES_to_rebuild_a_retired_epoch():
    """The differential oracle, inverted at 3A++.2.

    Before that unit this regenerated the corpus and asserted byte equality,
    with the note that a deliberate migration "must update the differential
    test explicitly -- not regenerate this corpus silently."

    The freeze script has its OWN guard for this: `build()` compares the live
    `EVIDENCE_DOMAIN` against the epoch it freezes and raises rather than
    emitting a corpus mislabelled as v4. That refusal is now the assertion --
    a stronger one, because it is enforced by the script itself rather than by
    a test remembering to check.
    """
    with pytest.raises(RuntimeError) as exc:
        _generator().build()
    message = str(exc.value)
    assert "drift-source-evidence-manifest-v5" in message
    assert "drift-source-evidence-manifest-v4" in message
    assert "BEFORE the migration to v5" in message


def test_the_frozen_digests_no_longer_match_the_LIVE_ones():
    """Named per case, so a reader sees WHICH cases moved -- all of them.

    Rebuilding each frozen case and re-digesting it under the live v5 epoch
    must differ from the recorded v4 digest. `test_source_evidence_epoch_v5.py`
    proves that ONLY the epoch metadata changed; this proves the digest did.
    """
    from genomic_variant_classifier.provenance import (
        ArtifactKind, CoordinateContext, CoordinateContextKind,
        SourceArtifactIdentity, SourceArtifactKey, SourceDependency,
        SourceEvidenceManifest, SourceRole)

    frozen = _doc()
    unchanged = []
    for name, case in sorted(frozen["cases"].items()):
        deps = []
        for dep in case["canonical_record"]["dependencies"]:
            rec = dep["identity"]
            ctx = rec["coordinate_context"]
            context = (
                CoordinateContext.assembly(ctx["identifier"])
                if CoordinateContextKind(ctx["kind"])
                is CoordinateContextKind.GENOMIC_ASSEMBLY
                else CoordinateContext.build_independent())
            key = rec["key"]
            deps.append(SourceDependency(
                identity=SourceArtifactIdentity(
                    key=SourceArtifactKey(key["source"],
                                          ArtifactKind(key["artifact_kind"]),
                                          key["product"] or None),
                    release_id=rec["release_id"],
                    coordinate_context=context,
                    artifact_sha256=rec["artifact_sha256"]),
                roles=frozenset(SourceRole(r) for r in dep["roles"])))
        if SourceEvidenceManifest.of(tuple(deps)).digest == case["digest"]:
            unchanged.append(name)
    assert not unchanged, (
        "these cases still digest to their v4 value: {}".format(unchanged))


