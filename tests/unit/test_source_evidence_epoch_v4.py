@pytest.mark.parametrize("name", _names())
def test_the_frozen_digest_derives_from_the_frozen_RECORD(name):
    """The strongest property this corpus has.

    The digest is not merely stored beside the record -- it is REPRODUCED from
    it, so an edited record cannot keep a stale digest and pass.
    """
    case = _doc()["cases"][name]
    assert domain_digest(_doc()["domain"], case["canonical_record"]) \
        == case["digest"]


@pytest.mark.parametrize("name", _names())
def test_the_record_is_CANONICAL_json(name):
    """Re-serialising must reproduce the same bytes, at any nesting depth."""
    case = _doc()["cases"][name]
    once = canonical_json(case["canonical_record"])
    twice = canonical_json(json.loads(once.decode("ascii")))
    assert once == twice


