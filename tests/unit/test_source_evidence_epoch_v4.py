def test_the_corpus_declares_the_v4_epoch():
    d = _doc()
    assert d["identity_family"] == "source_evidence_manifest"
    assert d["domain"] == "drift-source-evidence-manifest-v4"
    assert d["embedded_schema_version"] == 3
    assert d["case_count"] == len(d["cases"]) == 13


def test_the_HISTORICAL_DEFECT_is_recorded_not_cleaned():
    """Section 10: turn the historical defect into evidence.

    A future engineer must be able to determine why v4 emitted schema 3
    without archaeology.
    """
    d = _doc()
    condition = d["known_historical_condition"]
    assert "differ" in condition
    assert "schema_version" in condition
    assert "two writable declarations" in condition.lower()
    assert d["domain"].endswith("-v4")
    assert d["embedded_schema_version"] == 3
    for case in d["cases"].values():
        assert case["canonical_record"]["schema_version"] == 3


def test_the_corpus_records_a_RETIRED_epoch():
    """INVERTED at Phase 1C Unit 3A++.2, exactly as this file anticipated.

    Before that unit this read `EVIDENCE_DOMAIN == _doc()["domain"]`, with the
    note that "after 3A++.2 this assertion must be INVERTED by that unit,
    which is precisely how the corpus proves the migration happened rather
    than assuming it."

    It has been. The corpus now records a RETIRED epoch, and that is its
    purpose: v4 keeps meaning what v4 historically meant.
    """
    assert EVIDENCE_DOMAIN != _doc()["domain"], (
        "the live domain still equals the frozen one; the v5 migration did "
        "not happen, and this corpus is not yet a historical record")
    assert _doc()["domain"] == "drift-source-evidence-manifest-v4"
    assert EVIDENCE_DOMAIN == "drift-source-evidence-manifest-v5"


