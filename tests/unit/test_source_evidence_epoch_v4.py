_FIX = (Path(__file__).resolve().parents[2] / "tests" / "fixtures"
        / "source_evidence_epoch_v4" / "epoch.json")

pytestmark = pytest.mark.skipif(
    not _FIX.is_file(),
    reason="the v4 epoch corpus is absent; it is generated by "
           "scripts/dev/freeze_source_evidence_epoch.py and MUST be present "
           "in the repository -- this must not skip in CI")


def _doc() -> dict:
    return json.loads(_FIX.read_text(encoding="utf-8"))


def _names() -> list:
    return sorted(_doc()["cases"]) if _FIX.is_file() else []


